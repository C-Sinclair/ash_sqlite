  @impl true
  # The temporal arm is compiled out entirely against a released ash, where
  # `temporal?/1` is a constant false and the branch is dead code.
  if AshSqlite.Temporal.supported?() do
    def bulk_create(resource, stream, options) do
      if options[:upsert?] && AshSqlite.Temporal.temporal?(resource) do
        temporal_bulk_upsert(resource, stream, options)
      else
        do_bulk_create(resource, stream, options)
      end
    end
  else
    def bulk_create(resource, stream, options), do: do_bulk_create(resource, stream, options)
  end

  if AshSqlite.Temporal.supported?() do
    # SQLite cannot `ON CONFLICT` its way to a temporal upsert (see `temporal_upsert/3`),
    # and `bulk_create/3` builds one whenever `upsert?` is set. Each changeset is resolved
    # on its own instead, inside one transaction.
    defp temporal_bulk_upsert(resource, stream, options) do
      changesets = Enum.to_list(stream)
      repo = AshSql.dynamic_repo(resource, AshSqlite.SqlImplementation, Enum.at(changesets, 0))
      keys = options[:upsert_keys] || Ash.Resource.Info.primary_key(resource)

      AshSqlite.Temporal.transactionally(repo, fn ->
        changesets
        |> Enum.reduce_while({:ok, []}, fn changeset, {:ok, acc} ->
          case do_temporal_upsert(repo, resource, changeset, keys, options[:upsert_fields]) do
            # Ash correlates a bulk result to its changeset by this metadata, and drops a
            # record that does not carry it.
            {:ok, record} ->
              {:cont, {:ok, [tag_bulk_record(record, changeset) | acc]}}

            {:error, error} ->
              {:halt, {:error, error}}
          end
        end)
        |> case do
          {:ok, records} ->
            if options[:return_records?], do: {:ok, Enum.reverse(records)}, else: {:ok, []}

          other ->
            other
        end
      end)
    end

    defp tag_bulk_record(record, changeset) do
      case changeset.context do
        %{bulk_create: %{ref: ref}} -> Ash.Resource.put_metadata(record, :bulk_action_ref, ref)
        _other -> record
      end
    end
  end

  defp do_bulk_create(resource, stream, options) do
    # Cell-wise default values are not supported on INSERT statements by SQLite
    # This requires that we group changesets by what attributes are changing
    # And *omit* any defaults instead of using something like `(1, 2, DEFAULT)`
    # like we could with postgres
    stream
    |> Enum.map(&stamp_period(resource, &1))
    |> Enum.group_by(&Map.keys(&1.attributes))
    |> Enum.reduce_while({:ok, []}, fn {_, changesets}, {:ok, acc} ->
      repo = AshSql.dynamic_repo(resource, AshSqlite.SqlImplementation, Enum.at(changesets, 0))
      opts = AshSql.repo_opts(repo, AshSqlite.SqlImplementation, nil, options[:tenant], resource)

      opts =
        if options.return_records? do
          returning =
            case options[:action_select] do
              nil -> true
              [] -> Ash.Resource.Info.primary_key(resource)
              fields -> fields
            end

          Keyword.put(opts, :returning, returning)
        else
          opts
        end

      opts =
        if options[:upsert?] do
          # Ash groups changesets by atomics before dispatching them to the data layer
          # this means that all changesets have the same atomics
          %{atomics: atomics, filter: filter} = Enum.at(changesets, 0)

          query = from(row in resource, as: ^0)

          query =
            query
            |> AshSql.Bindings.default_bindings(resource, AshSqlite.SqlImplementation)

          upsert_set =
            upsert_set(
              resource,
              changesets,
              options[:upsert_keys] || Ash.Resource.Info.primary_key(resource),
              options
            )

          on_conflict =
            case AshSql.Atomics.query_with_atomics(
                   resource,
                   query,
                   filter,
                   atomics,
                   %{},
                   upsert_set
                 ) do
              {:empty, _query} ->
                raise "Cannot upsert with no fields to specify in the upsert statement. This can only happen on resources without a primary key."

              {:ok, query} ->
                query

              {:error, error} ->
                raise Ash.Error.to_ash_error(error)
            end

          opts
          |> Keyword.put(:on_conflict, on_conflict)
          |> Keyword.put(
            :conflict_target,
            conflict_target(
              resource,
              options[:upsert_keys] || Ash.Resource.Info.primary_key(resource)
            )
          )
        else
          opts
        end

      create_atomics = Map.get(Enum.at(changesets, 0), :create_atomics, [])

      atomic_insert_values =
        if create_atomics != [] do
          query = from(row in resource, as: ^0)

          query =
            query
            |> AshSql.Bindings.default_bindings(resource, AshSqlite.SqlImplementation)

          case AshSql.Atomics.atomics_to_insert_values(resource, query, create_atomics) do
            {:ok, values} -> values
            {:error, error} -> raise Ash.Error.to_ash_error(error)
          end
        else
          %{}
        end

      ecto_changesets =
        Enum.map(changesets, fn cs ->
          Map.merge(cs.attributes, atomic_insert_values)
        end)

      source =
        if table = Enum.at(changesets, 0).context[:data_layer][:table] do
          {table, resource}
        else
          resource
        end

      source
      |> repo.insert_all(ecto_changesets, opts)
      |> case do
        {_, nil} ->
          {:cont, {:ok, acc}}

        {_, results} ->
          if options[:single?] do
            {:cont, {:ok, acc ++ results}}
          else
            {:cont,
             {:ok,
              acc ++
                Enum.zip_with(results, changesets, fn result, changeset ->
                  Ash.Resource.put_metadata(
                    result,
                    :bulk_action_ref,
                    changeset.context.bulk_create.ref
                  )
                end)}}
          end
      end
    end)
    |> case do
      {:ok, records} ->
        if options[:return_records?] do
          {:ok, records}
        else
          :ok
        end

      {:error, error} ->
        {:error, error}
    end
  rescue
    e ->
      changeset = Ash.Changeset.new(resource)

      handle_raised_error(
        e,
        __STACKTRACE__,
        {:bulk_create, ecto_changeset(changeset.data, changeset, :create, false)},
        resource
      )
  end

  defp upsert_set(resource, changesets, keys, options) do
    attributes_changing_anywhere =
      changesets |> Enum.flat_map(&Map.keys(&1.attributes)) |> Enum.uniq()

    update_defaults = update_defaults(resource)
    # We can't reference EXCLUDED if at least one of the changesets in the stream is not
    # changing the value (and we wouldn't want to even if we could as it would be unnecessary)

    upsert_fields =
      (options[:upsert_fields] || []) |> Enum.filter(&(&1 in attributes_changing_anywhere))

    fields_to_upsert =
      upsert_fields --
        (Keyword.keys(Enum.at(changesets, 0).atomics) -- keys)

    fields_to_upsert =
      case fields_to_upsert do
        [] ->
          keys

        fields_to_upsert ->
          # Include fields with update_defaults (e.g. update_timestamp)
          # even if they aren't in the changeset attributes or upsert_fields.
          # These fields should always be refreshed when an upsert modifies fields.
          # Can be disabled via touch_update_defaults?: false in the changeset
          # context (either in [:private] or [:data_layer]) or via options map
          touch_update_defaults? =
            Map.get(options, :touch_update_defaults?, true) &&
              Enum.at(changesets, 0).context[:private][:touch_update_defaults?] != false &&
              Enum.at(changesets, 0).context[:data_layer][:touch_update_defaults?] != false

          if touch_update_defaults? do
            update_default_fields =
              update_defaults
              |> Keyword.keys()
              |> Enum.reject(&(&1 in fields_to_upsert or &1 in keys))

            fields_to_upsert ++ update_default_fields
          else
            fields_to_upsert
          end
      end

    fields_to_upsert
    |> Enum.uniq()
    |> Enum.map(fn upsert_field ->
      # for safety, we check once more at the end that all values in
      # upsert_fields are names of attributes. This is because
      # below we use `literal/1` to bring them into the query
      if is_nil(resource.__schema__(:type, upsert_field)) do
        raise "Only attribute names can be used in upsert_fields"
      end

      case Keyword.fetch(update_defaults, upsert_field) do
        {:ok, default} ->
          if upsert_field in upsert_fields do
            {upsert_field,
             Ecto.Query.dynamic(
               [],
               fragment(
                 "COALESCE(EXCLUDED.?, ?)",
                 identifier(^to_string(get_source_for_upsert_field(upsert_field, resource))),
                 ^default
               )
             )}
          else
            {upsert_field, default}
          end

        :error ->
          {upsert_field,
           Ecto.Query.dynamic(
             [],
             fragment(
               "EXCLUDED.?",
               identifier(^to_string(get_source_for_upsert_field(upsert_field, resource)))
             )
           )}
      end
    end)
  end

  @doc false
  def get_source_for_upsert_field(field, resource) do
    case Ash.Resource.Info.attribute(resource, field) do
      %{source: source} when not is_nil(source) ->
        source

      _ ->
        field
    end
  end

  @impl true
  def create(resource, changeset) do
    changeset = %{
      changeset
      | data:
          Map.update!(
            changeset.data,
            :__meta__,
            &Map.put(&1, :source, table(resource, changeset))
          )
    }

    case bulk_create(resource, [changeset], %{
           single?: true,
           tenant: changeset.tenant,
           return_records?: true
         }) do
      {:ok, [result]} ->
        {:ok, result}

      {:error, error} ->
        {:error, error}
    end
  end

  # A temporal create establishes the period `as_of` names. The period attribute is
  # never accepted as action input, so this is the only place it is set on a create.
  defp stamp_period(resource, changeset) do
    if AshSqlite.Temporal.temporal?(resource) do
      attribute = AshSqlite.Temporal.attribute(resource)
      as_of = AshSqlite.Temporal.write_instant(resource, changeset)
      period = AshSqlite.Temporal.period(resource, as_of)

      # `put_new`: a temporal upsert that misses has already bounded the period above
      # by the version that follows it, and must not have that replaced by `[as_of, oo)`.
      %{changeset | attributes: Map.put_new(changeset.attributes, attribute, period)}
    else
      changeset
    end
  end

  defp ecto_changeset(record, changeset, type, table_error?) do
    filters =
      if changeset.action_type == :create do
        %{}
      else
        changeset.resource
        |> Ash.Resource.Info.primary_key()
        |> Enum.reduce(%{}, fn key, filters ->
          Map.put(filters, key, Map.get(record, key))
        end)
      end

    attributes =
      changeset.resource
      |> Ash.Resource.Info.attributes()
      |> Enum.map(& &1.name)

    attributes_to_change =
      Enum.reject(attributes, fn attribute ->
        Keyword.has_key?(changeset.atomics, attribute)
      end)

    ecto_changeset =
      record
      |> to_ecto()
      |> set_table(changeset, type, table_error?)
      |> Ecto.Changeset.cast(%{}, [])
      |> force_changes(Map.take(changeset.attributes, attributes_to_change))
      |> Map.update!(:filters, &Map.merge(&1, filters))
      |> add_configured_foreign_key_constraints(record.__struct__)
      |> add_unique_indexes(record.__struct__, changeset)
      |> add_exclusion_constraints(record.__struct__)

    case type do
      :create ->
        ecto_changeset
        |> add_my_foreign_key_constraints(record.__struct__)

      type when type in [:upsert, :update] ->
        ecto_changeset
        |> add_my_foreign_key_constraints(record.__struct__)
        |> add_related_foreign_key_constraints(record.__struct__)

      :delete ->
        ecto_changeset
        |> add_related_foreign_key_constraints(record.__struct__)
    end
  end

  defp force_changes(changeset, changes) do
    Enum.reduce(changes, changeset, fn {key, value}, acc ->
      Ecto.Changeset.force_change(acc, key, value)
    end)
  end

